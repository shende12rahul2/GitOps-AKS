#!/usr/bin/env bash
# Generates the non-secret "environment contract" consumed by the GitOps repo
# (aks-gitops-deployment/environments/<env>/infrastructure.yaml) from Terraform
# outputs of the three layers. Contains IDs, names, CIDRs and endpoints only.
#
# Usage:
#   ./scripts/export-gitops-values.sh <env> [argocd-client-id] [airflow-client-id] > ../aks-gitops-deployment/environments/<env>/infrastructure.yaml
# The SSO client IDs are printed by bootstrap/entra/create-app-registrations.sh.
set -euo pipefail
env="${1:?environment}"; argocd_client="${2:-00000000-0000-0000-0000-000000000000}"; airflow_client="${3:-00000000-0000-0000-0000-000000000000}"
root="$(cd "$(dirname "$0")/.." && pwd)/environments/${env}"
project="${PROJECT:-akspoc}"

out() { if [ -n "${TF_OUTPUTS_DIR:-}" ]; then cat "$TF_OUTPUTS_DIR/$1.json"; else (cd "$root/$1" && terraform output -json); fi; }

jq -n --argjson f "$(out foundation)" --argjson p "$(out platform)" --argjson d "$(out data)" \
      --arg env "$env" --arg project "$project" --arg argocd "$argocd_client" --arg airflow "$airflow_client" '
{
  global: {
    environment: $env,
    tenantId: $p.tenant_id.value,
    keyVaultName: $p.key_vault_name.value,
    acrLoginServer: $p.acr_login_server.value,
    dnsZone: $f.app_dns_zone_name.value,
    ingress: {
      mode: (if $p.ingress_mode.value == "agic" then "agic" else "internal" end),
      privateIp: $p.ingress_private_ip.value,
      gatewaySubnetCidr: $f.subnet_cidrs.value.appgw,
      publicApp: $f.appgw_public_frontend_enabled.value,
      hosts: $p.hostnames.value
    },
    network: {
      vnetCidr: ($f.subnet_cidrs.value.aks_nodes | split(".") | .[0:2] | join(".") + ".0.0/16"),
      nodeSubnetCidr: $f.subnet_cidrs.value.aks_nodes,
      privateEndpointSubnetCidr: $f.subnet_cidrs.value.private_endpoints,
      postgresSubnetCidr: $f.subnet_cidrs.value.postgresql,
      podCidr: "192.168.0.0/16"
    },
    workloadIdentities: ($p.workload_identities.value | with_entries(.value = {name: .value.name, clientId: .value.client_id, principalId: .value.principal_id})),
    postgres: { host: $d.postgresql_fqdn.value, port: 5432 },
    redis: { host: $d.redis_hostname.value, port: $d.redis_port.value },
    azureFiles: {
      storageAccount: $d.storage_account_name.value,
      resourceGroup: $d.resource_group_name.value,
      kubeletClientId: $p.kubelet_identity_client_id.value,
      shares: $d.file_share_names.value
    },
    entraGroups: {
      platformAdmins: $p.entra_group_object_ids.value.platform_admins,
      devops: $p.entra_group_object_ids.value.devops,
      developers: $p.entra_group_object_ids.value.developers,
      developersName: ("grp-" + $project + "-developers"),
      qa: $p.entra_group_object_ids.value.qa,
      qaName: ("grp-" + $project + "-qa"),
      readers: $p.entra_group_object_ids.value.readers
    },
    sso: { argocdClientId: $argocd, airflowClientId: $airflow }
  }
}' | python3 -c 'import sys,json,yaml; print("# GENERATED by aks-infrastructure-iac/scripts/export-gitops-values.sh - do not edit by hand.\n" + yaml.safe_dump(json.load(sys.stdin), sort_keys=False))'
